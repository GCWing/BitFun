import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'src/shared/canvas/sdk-contract.json');
const check = process.argv.includes('--check');
const contract = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));

const componentNames = Object.keys(contract.components);
const runtimeExports = [...componentNames, ...contract.nonComponentExports];

function rustString(value) {
  return JSON.stringify(value);
}

function rustSlice(values) {
  return `&[${values.map(rustString).join(', ')}]`;
}

function generateRust() {
  const componentArms = componentNames
    .map(name => `        ${rustString(name)} => Some(${rustSlice(contract.components[name].props)}),`)
    .join('\n');
  const backingArms = componentNames
    .map(name => `        ${rustString(name)} => Some(${rustString(contract.components[name].backing)}),`)
    .join('\n');
  const appearanceArms = Object.entries(contract.appearanceTokenGroups)
    .map(([group, values]) => `        ${rustString(group)} => (${rustSlice(values)}).contains(&token),`)
    .join('\n');
  return `// Generated by scripts/generate-canvas-sdk-contract.mjs. Do not edit.\n\n` +
    `pub const OPENBITFUN_CANVAS_SDK_VERSION: &str = ${rustString(contract.sdkVersion)};\n` +
    `pub const OPENBITFUN_CANVAS_RUNTIME_VERSION: &str = ${rustString(contract.runtimeVersion)};\n` +
    `pub const CANVAS_SDK_RUNTIME_EXPORTS: &[&str] = ${rustSlice(runtimeExports)};\n` +
    `pub const CANVAS_SDK_COMMON_PROPS: &[&str] = ${rustSlice(contract.commonProps)};\n\n` +
    `pub fn canvas_sdk_component_props(component: &str) -> Option<&'static [&'static str]> {\n    match component {\n${componentArms}\n        _ => None,\n    }\n}\n\n` +
    `pub fn canvas_sdk_component_backing(component: &str) -> Option<&'static str> {\n    match component {\n${backingArms}\n        _ => None,\n    }\n}\n\n` +
    `pub fn canvas_appearance_token_group_allows(group: &str, token: &str) -> bool {\n    match group {\n${appearanceArms}\n        _ => false,\n    }\n}\n`;
}

function formatRust(source) {
  const result = spawnSync('rustfmt', ['--emit', 'stdout', '--edition', '2021'], {
    encoding: 'utf8',
    input: source,
  });
  if (result.status !== 0) {
    throw new Error(`rustfmt failed while generating the Canvas SDK contract: ${result.stderr || result.stdout}`);
  }
  return result.stdout;
}

function generateTypeScript() {
  return `// Generated by scripts/generate-canvas-sdk-contract.mjs. Do not edit.\n` +
    `export const canvasSdkContract = ${JSON.stringify({ ...contract, runtimeExports }, null, 2)} as const;\n\n` +
    `export const CANVAS_SDK_VERSION = canvasSdkContract.sdkVersion;\n` +
    `export const CANVAS_RUNTIME_VERSION = canvasSdkContract.runtimeVersion;\n` +
    `export const CANVAS_SDK_RUNTIME_EXPORTS = canvasSdkContract.runtimeExports;\n`;
}

const outputs = [
  {
    path: 'src/crates/contracts/product-domains/src/canvas/sdk_contract.generated.rs',
    content: formatRust(generateRust()),
  },
  {
    path: 'src/web-ui/src/tools/openbitfun-canvas/runtime/sdk/contract.generated.ts',
    content: generateTypeScript(),
  },
  {
    path: 'src/crates/assembly/core/builtin_skills/openbitfun-canvas/sdk/sdk-contract.generated.json',
    content: `${JSON.stringify({ ...contract, runtimeExports }, null, 2)}\n`,
  },
];

let stale = false;
for (const output of outputs) {
  const absolutePath = path.join(root, output.path);
  const current = fs.existsSync(absolutePath) ? fs.readFileSync(absolutePath, 'utf8').replaceAll('\r\n', '\n') : '';
  const expected = output.content.replaceAll('\r\n', '\n');
  if (current === expected) continue;
  if (check) {
    console.error(`[canvas-sdk:check] stale generated file: ${output.path}`);
    stale = true;
    continue;
  }
  fs.mkdirSync(path.dirname(absolutePath), { recursive: true });
  fs.writeFileSync(absolutePath, expected);
  console.log(`[canvas-sdk:generate] wrote ${output.path}`);
}

if (stale) process.exitCode = 1;
