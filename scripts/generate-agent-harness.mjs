import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contract = JSON.parse(fs.readFileSync(path.join(root, 'src/shared/agent-harness/contract.json'), 'utf8'));
const entries = contract.harnesses;
const quote = JSON.stringify;
const banner = '// Generated by scripts/generate-agent-harness.mjs. Edit the shared contract instead.\n';
const ts = `${banner}
export const HARNESS_IDS = [${entries.map(entry => quote(entry.id)).join(', ')}] as const;
export type HarnessId = typeof HARNESS_IDS[number];
const aliases: ReadonlyMap<string, HarnessId> = new Map([
${entries.flatMap(entry => [entry.id, ...entry.legacyIds].map(id => `  [${quote(id)}, ${quote(entry.id)}],`)).join('\n')}
]);
const legacyWireIds: Record<HarnessId, string> = {
${entries.map(entry => `  ${entry.id}: ${quote(entry.legacyWireId)},`).join('\n')}
};
const configAliases: ReadonlyMap<string, HarnessId> = new Map([
${entries.flatMap(entry => (entry.legacyConfigIds ?? []).map(id => `  [${quote(id)}, ${quote(entry.id)}],`)).join('\n')}
]);
export function isHarnessId(id: string): id is HarnessId {
  return (HARNESS_IDS as readonly string[]).includes(id);
}
/** Use only at a built-in identity boundary; source-qualified/custom IDs stay intact. */
export function canonicalHarnessId(id: string | null | undefined): HarnessId | null {
  const key = id?.trim();
  return key ? aliases.get(key) ?? aliases.get(key.toLowerCase()) ?? null : null;
}
export function canonicalAgentId(id: string): string {
  return canonicalHarnessId(id) ?? id;
}
export function legacyAgentWireId(id: string): string {
  const harness = canonicalHarnessId(id);
  return harness ? legacyWireIds[harness] : id;
}
export function canonicalAgentConfigId(id: string): string {
  return configAliases.get(id) ?? canonicalAgentId(id);
}
`;
const rs = `${banner}
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum HarnessId {
${entries.map(entry => `    ${entry.legacyIds.map(id => `#[serde(alias = ${quote(id)})]`).join('\n    ')}\n    ${entry.id},`).join('\n')}
}

impl HarnessId {
    pub const ALL: [Self; ${entries.length}] = [
${entries.map(entry => `        Self::${entry.id},`).join('\n')}
    ];
    pub const fn as_str(self) -> &'static str {
        match self {
${entries.map(entry => `            Self::${entry.id} => ${quote(entry.id)},`).join('\n')}
        }
    }
    pub fn from_legacy_id(id: &str) -> Option<Self> {
        match id.trim().to_ascii_lowercase().as_str() {
${entries.map(entry => `            ${[...new Set([entry.id, ...entry.legacyIds].map(id => id.toLowerCase()))].map(quote).join(' | ')} => Some(Self::${entry.id}),`).join('\n')}
            _ => None,
        }
    }
    pub const fn legacy_wire_id(self) -> &'static str {
        match self {
${entries.map(entry => `            Self::${entry.id} => ${quote(entry.legacyWireId)},`).join('\n')}
        }
    }
    pub const fn legacy_ids(self) -> &'static [&'static str] {
        match self {
${entries.map(entry => `            Self::${entry.id} => &[${entry.legacyIds.map(quote).join(', ')}],`).join('\n')}
        }
    }
}

/// Normalize a built-in identity at storage/protocol boundaries. Unknown IDs survive.
pub fn canonical_agent_id(id: &str) -> &str {
    HarnessId::from_legacy_id(id)
        .map(HarnessId::as_str)
        .unwrap_or(id)
}

pub fn canonical_agent_config_id(id: &str) -> &str {
    match id {
${entries.flatMap(entry => (entry.legacyConfigIds ?? []).map(id => `        ${quote(id)} => ${quote(entry.id)},`)).join('\n')}
        _ => canonical_agent_id(id),
    }
}

pub fn deserialize_agent_id<'de, D: serde::Deserializer<'de>>(
    deserializer: D,
) -> Result<String, D::Error> {
    let id = String::deserialize(deserializer)?;
    Ok(canonical_agent_id(&id).to_owned())
}

pub fn deserialize_optional_agent_id<'de, D: serde::Deserializer<'de>>(
    deserializer: D,
) -> Result<Option<String>, D::Error> {
    Ok(Option::<String>::deserialize(deserializer)?.map(|id| canonical_agent_id(&id).to_owned()))
}
`;
for (const [relative, content] of [
  ['src/shared/agent-harness/contract.generated.ts', ts],
  ['src/crates/contracts/core-types/src/agent_identity.rs', rs],
]) {
  const output = path.join(root, relative);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== content) {
      throw new Error(`Generated Harness contract is stale: ${relative}`);
    }
  } else {
    fs.writeFileSync(output, content);
  }
}
