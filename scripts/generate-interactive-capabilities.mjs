function buildTechnicalCoverage(source, capabilityIds) {
  const registrations = parseRegisteredCommands(readFileSync(DESKTOP_LIB, 'utf8'));
  const duplicateIds = registrations.map(({ id }) => id).filter((id, index, all) => all.indexOf(id) !== index);
  if (duplicateIds.length) throw new Error(`Duplicate registered commands: ${duplicateIds.join(', ')}`);
  const functions = collectTauriFunctions();
  const policies = parseRemotePolicies(readFileSync(REMOTE_POLICY, 'utf8'));
  const registeredSet = new Set(registrations.map(({ id }) => id));
  const missingPolicies = [...registeredSet].filter((id) => !policies.has(id));
  const extraPolicies = [...policies.keys()].filter((id) => !registeredSet.has(id));
  if (missingPolicies.length || extraPolicies.length) {
    throw new Error([
      missingPolicies.length ? `Commands missing remote policy: ${missingPolicies.join(', ')}` : '',
      extraPolicies.length ? `Policies without commands: ${extraPolicies.join(', ')}` : '',
    ].filter(Boolean).join('\n'));
  }

  const commands = registrations.map(({ id, rustPath }) => {
    const resolved = resolveRegisteredFunction(id, rustPath, functions.get(id) ?? []);
    const moduleId = commandModule(resolved.sourceFile);
    const owner = source.implementationOwners[moduleId];
    if (!owner) throw new Error(`Tauri module ${moduleId} has no reviewed semantic owner`);
    if (owner.capabilityId !== null && !capabilityIds.has(owner.capabilityId)) {
      throw new Error(`Tauri module ${moduleId} targets unknown capability ${owner.capabilityId}`);
    }
    return {
      id,
      moduleId,
      capabilityId: owner.capabilityId,
      visibility: owner.capabilityId === null ? 'internal' : 'implementation',
      rustPath,
      sourceFile: resolved.sourceFile,
      signature: resolved.signature,
      remoteWorkspacePolicy: policies.get(id),
    };
  }).sort((left, right) => left.id.localeCompare(right.id));

  const actualModules = new Map();
  for (const command of commands) {
    const values = actualModules.get(command.moduleId) ?? [];
    values.push(command);
    actualModules.set(command.moduleId, values);
  }
  const staleOwners = Object.keys(source.implementationOwners).filter((moduleId) => !actualModules.has(moduleId));
  if (staleOwners.length) throw new Error(`Semantic owners without Tauri modules: ${staleOwners.join(', ')}`);
  for (const [moduleId, values] of actualModules) {
    const reviewed = source.implementationOwners[moduleId].reviewedCommandCount;
    if (reviewed !== values.length) {
      throw new Error(
        `Tauri module ${moduleId} changed from its reviewed count ${reviewed} to ${values.length}. `
        + 'Review whether this is a new user feature or an existing implementation detail, then update the one semantic source.',
      );
    }
  }
  return commands;
}

function searchTerms(capability, category) {
  return [...new Set([
    capability.id,
    capability.titleZh,
    capability.titleEn,
    category.titleZh,
    category.titleEn,
    ...capability.keywordsZh,
    ...capability.keywordsEn,
    ...capability.highlightsZh,
    ...capability.highlightsEn,
    ...capability.items.flatMap((item) => [item.titleZh, item.titleEn]),
  ])];
}

export function buildCapabilityCatalog() {
  const source = JSON.parse(readFileSync(SOURCE_PATH, 'utf8'));
  const capabilityIds = validateSource(source);
  const interactionInventory = validateInteractionContract(source);
  const technicalCommands = buildTechnicalCoverage(source, capabilityIds);
  validateDocumentationEvidence(source, technicalCommands);

  const runtimeCapabilities = source.capabilities.map((capability) => {
    const category = source.categories[capability.categoryId];
    return {
      ...capability,
      items: capability.items.map(runtimeItem),
      operations: capability.operations ?? [],
      options: capability.options ?? [],
      searchTerms: searchTerms(capability, category),
      docsUrl: `${source.origin}/capabilities/${capability.id}/`,
    };
  });
  const publicCapabilities = runtimeCapabilities.map((capability) => ({
    ...capability,
    operations: capability.operations.map(publicOperation),
    options: capability.options.map(publicOption),
  }));
  const digest = createHash('sha256')
    .update(JSON.stringify({ categories: source.categories, capabilities: publicCapabilities }))
    .digest('hex');
  const common = {
    schemaVersion: source.schemaVersion,
    product: source.product,
    title: source.title,
    origin: source.origin,
    source: toPosix(path.relative(REPO_ROOT, SOURCE_PATH)),
    digest,
    counts: {
      features: publicCapabilities.filter(({ kind }) => kind === 'feature').length,
      settings: publicCapabilities.filter(({ kind }) => kind === 'setting').length,
      userFacing: publicCapabilities.length,
      documentedItems: publicCapabilities.reduce((total, capability) => total + capability.items.length, 0),
    },
    categories: source.categories,
  };
  return {
    publicCatalog: { ...common, capabilities: publicCapabilities },
    runtimeCatalog: { ...common, capabilities: runtimeCapabilities },
    technicalMap: {
      schemaVersion: 1,
      generatedFrom: toPosix(path.relative(REPO_ROOT, SOURCE_PATH)),
      catalogDigest: digest,
      commandCount: technicalCommands.length,
      commands: technicalCommands,
    },
    interactionMap: {
      schemaVersion: 1,
      generatedFrom: toPosix(path.relative(REPO_ROOT, SOURCE_PATH)),
      catalogDigest: digest,
      ...interactionInventory,
    },
  };
}

function destinationText(destination) {
  if (destination.kind === 'settings') return 'BitFun 设置';
  if (destination.kind === 'action') return 'BitFun 功能入口';
  if (destination.kind === 'scene') return 'BitFun 对应场景';
  return 'BitFun 内的对应控制界面';
}

function schemaLabel(schema) {
  if (schema.enum) return schema.enum.map((value) => `\`${value}\``).join(' / ');
  const range = schema.minimum !== undefined || schema.maximum !== undefined
    ? ` (${schema.minimum ?? '…'}–${schema.maximum ?? '…'})`
    : '';
  return `\`${schema.type}\`${range}`;
}

function renderCapabilityMarkdown(capability) {
  const kindZh = capability.kind === 'feature' ? '功能' : '设置';
  const kindEn = capability.kind === 'feature' ? 'Feature' : 'Setting';
  const operations = capability.operations.length
    ? capability.operations.map((operation) =>
      `| ${operation.titleZh} / ${operation.titleEn} | ${operation.descriptionZh} | ${operation.descriptionEn} |`,
    ).join('\n')
    : '| 打开对应界面 / Open the UI | 进入 BitFun 中对应的功能界面。 | Open the matching feature in BitFun. |';
  const options = capability.options.length
    ? capability.options.map((option) =>
      `| ${option.titleZh} / ${option.titleEn} | ${schemaLabel(option.valueSchema)} | ${option.descriptionZh} | ${option.descriptionEn} |`,
    ).join('\n')
    : '| 在界面中配置 / Configure in the UI | — | 此页面的设置在对应界面中完成。 | Configure this page in its matching UI. |';
  const steps = capability.stepsZh.map((step, index) => `${index + 1}. ${step}\n   ${capability.stepsEn[index] ?? ''}`).join('\n');
  const inventory = capability.items.map((item) => `- ${item.titleZh}\n  - ${item.titleEn}`).join('\n');
  const examples = capability.agentExamplesZh.map((item, index) => `- “${item}”\n  - “${capability.agentExamplesEn[index] ?? ''}”`).join('\n');
  return `${GENERATED_MARKER}
---
id: ${capability.id}
kind: ${capability.kind}
category: ${capability.categoryId}
title_zh: ${JSON.stringify(capability.titleZh)}
title_en: ${JSON.stringify(capability.titleEn)}
---

# ${capability.titleZh} / ${capability.titleEn}

> ${kindZh} / ${kindEn}

${capability.summaryZh}

${capability.summaryEn}

## 完整功能清单 / Everything included

${inventory}

## 怎么用 / How to use it

${steps}

入口 / Entry: ${destinationText(capability.destination)}

## Agent 可替你做什么 / What an agent can do for you

| 操作 / Action | 中文说明 | English description |
| --- | --- | --- |
${operations}

## 可配置选项 / Configurable options

| 选项 / Option | 可用值 / Values | 中文说明 | English description |
| --- | --- | --- | --- |
${options}

## 可以直接对 Agent 说 / Try saying

${examples}

Agent 会先查找相关功能或设置，确认目标后再替你打开、执行或修改。完整能力目录不会预先塞进对话上下文。

The agent first finds the relevant feature or setting, confirms the target, and then opens, runs, or changes it for you. The full catalog is never embedded in the conversation context.
`;
}

function renderReadme(catalog, technicalMap, interactionMap) {
  return `${GENERATED_MARKER}
# BitFun 功能与设置目录 / BitFun Features & Settings

BitFun Playbook 当前包含 **${catalog.counts.features} 个功能**和 **${catalog.counts.settings} 个设置页**，共 **${catalog.counts.userFacing} 个**用户可理解的条目、**${catalog.counts.documentedItems} 项**有源码证据的子能力。每个条目有独立 Markdown，并直接服务于说明书网站、BitFun 全局搜索和 \`BitFunControl\` Agent 工具。

BitFun Playbook currently contains **${catalog.counts.features} features**, **${catalog.counts.settings} settings pages**, and **${catalog.counts.documentedItems}** source-backed sub-capabilities across **${catalog.counts.userFacing}** user-facing entries. Every entry has its own Markdown page and directly powers the website, in-app global search, and the \`BitFunControl\` agent tool.

## 唯一事实源 / Single source of truth

- 手工维护的唯一语义目录：\`${catalog.source}\`
- 生成的公开目录：\`docs/interactive-capabilities/capabilities.json\`
- 生成的前端运行目录：\`src/web-ui/src/app/global-search/generated/interactive-capabilities.json\`
- 生成的底层审计表：\`docs/interactive-capabilities/technical/tauri-command-map.json\`
- 生成的可见交互审计表：\`docs/interactive-capabilities/technical/ui-interaction-inventory.json\`

说明书、网站、搜索和 Agent 只看“功能 + 设置 + 子能力”。每项子能力都必须引用已注册 Tauri Command 或可解析的源码标记；这些证据不会进入公开目录。当前 **${technicalMap.commandCount}** 个 Tauri 命令，以及 **${interactionMap.fileCount}** 个产品交互源码文件中的 **${interactionMap.interactionCount}** 个交互候选，只用于实现覆盖审计。

Docs, website, search, and agents see only features, settings, and documented sub-capabilities. Every sub-capability must reference a registered Tauri command or a resolvable source marker; evidence is stripped from public projections. The **${technicalMap.commandCount}** Tauri commands and **${interactionMap.interactionCount}** interaction candidates across **${interactionMap.fileCount}** product UI source files remain implementation-audit evidence only.

## 控制边界 / Control boundary

- 每个功能或设置都有可执行的产品入口；存在多视图的设置页还必须把每个视图映射到至少一个子能力，搜索和 Agent 可携带子能力 ID 精确跳转。
- 简单、稳定且适合自动化的行为才声明为类型化 \`operations\` 或 \`options\`。复杂流程由 Agent 打开对应界面交给用户继续，不向 Agent 暴露原始 Tauri Command。
- \`BitFunControl list\` 一次返回完整的精简目录（目录上限 50 项）；\`search\` 默认只返回前 20 项。完整目录和 ${catalog.counts.documentedItems} 项子能力都不会写入 system prompt。
- Desktop 只有在前端控制监听器完成握手后才发布工具；CLI、Detached Dispatch 等没有交互界面的运行方式明确不提供该工具。只读 Agent 只能发现和读取目录。

- Every feature or setting has an executable product destination. Multi-view settings pages must map every registered view to at least one documented item, so search and agents can carry an item ID for exact navigation.
- Only simple, stable, automation-safe behavior becomes a typed \`operation\` or \`option\`. Complex flows open their owning UI instead of exposing raw Tauri commands to agents.
- One default \`BitFunControl list\` call returns the complete curated catalog (hard limit: 50); \`search\` defaults to 20 results. Neither the full catalog nor its ${catalog.counts.documentedItems} documented items enters the system prompt.
- Desktop advertises the tool only after the frontend control listener completes its readiness handshake. Headless surfaces such as CLI and Detached Dispatch explicitly omit it, and read-only agents may only discover and inspect entries.

## 防腐化门禁 / Anti-drift gates

- 设置页、产品动作与场景注册表必须全部映射到一个语义条目。
- 所有设置子视图必须有同源的子能力直达目标，失效的页签 ID 会阻断生成。
- 每个功能至少 6 项、每个设置至少 4 项子能力，且中英文、稳定 ID 与证据缺一不可。
- 当前操作处理器不接受参数；若目录误声明参数，生成会失败，避免 Agent 看到实际不会生效的参数。
- Tauri 模块命令数和用户可见交互源码摘要均为 reviewed contract；变化会让 \`capabilities:check\` 失败并给出新的摘要值。
- 维护者必须先核对功能清单与证据，再只在本语义源中更新 reviewed count/digest，随后运行 \`pnpm run capabilities:generate\`。

- Every settings page, product action, and scene registration must map to one semantic entry.
- Every settings subview needs a same-source item destination; stale view IDs fail generation.
- Features need at least six documented items and settings need at least four, each with bilingual text, a stable ID, and source evidence.
- Current operation handlers accept no arguments, and generation fails if the catalog advertises arguments that would be ignored.
- Reviewed Tauri module counts and the user-visible interaction-source digest fail \`capabilities:check\` on drift.
- Maintainers review the inventories and evidence first, update the reviewed count/digest only in this semantic source, then run \`pnpm run capabilities:generate\`.
`;
}

async function compareOrWrite(file, content, drift) {
  if (checkMode) {
    let actual = null;
    try { actual = await readFile(file, 'utf8'); } catch {}
    if (actual !== content) drift.push(toPosix(path.relative(REPO_ROOT, file)));
    return;
  }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, content, 'utf8');
}

async function generatedMarkdownFiles() {
  try {
    return (await readdir(DOCS_CAPABILITIES_ROOT, { withFileTypes: true }))
      .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
      .map((entry) => path.join(DOCS_CAPABILITIES_ROOT, entry.name));
  } catch {
    return [];
  }
}

async function main() {
  const { publicCatalog, runtimeCatalog, technicalMap, interactionMap } = buildCapabilityCatalog();
  const drift = [];
  await compareOrWrite(PUBLIC_CATALOG_PATH, `${JSON.stringify(publicCatalog, null, 2)}\n`, drift);
  await compareOrWrite(RUNTIME_CATALOG_PATH, `${JSON.stringify(runtimeCatalog, null, 2)}\n`, drift);
  await compareOrWrite(TECHNICAL_MAP_PATH, `${JSON.stringify(technicalMap, null, 2)}\n`, drift);
  await compareOrWrite(UI_INTERACTION_MAP_PATH, `${JSON.stringify(interactionMap, null, 2)}\n`, drift);
  await compareOrWrite(path.join(DOCS_ROOT, 'README.md'), renderReadme(publicCatalog, technicalMap, interactionMap), drift);

  const expectedDocs = new Set();
  for (const capability of publicCatalog.capabilities) {
    const file = path.join(DOCS_CAPABILITIES_ROOT, `${capability.id}.md`);
    expectedDocs.add(file);
    await compareOrWrite(file, renderCapabilityMarkdown(capability), drift);
  }
  for (const file of await generatedMarkdownFiles()) {
    if (expectedDocs.has(file)) continue;
    const content = await readFile(file, 'utf8');
    if (!content.startsWith(GENERATED_MARKER)) throw new Error(`Refusing to remove non-generated document: ${file}`);
    if (checkMode) drift.push(toPosix(path.relative(REPO_ROOT, file)));
    else await rm(file);
  }

  if (drift.length) {
    console.error('Interactive capability artifacts are stale or missing:');
    drift.sort().forEach((file) => console.error(`- ${file}`));
    console.error('Run: pnpm run capabilities:generate');
    process.exitCode = 1;
    return;
  }
  if (!quiet) {
    console.log(
      `${checkMode ? 'Verified' : 'Generated'} ${publicCatalog.counts.features} features + `
      + `${publicCatalog.counts.settings} settings; audited ${technicalMap.commandCount} Tauri commands `
      + `(${publicCatalog.digest.slice(0, 12)}).`,
    );
  }
}

if (path.resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) await main();
