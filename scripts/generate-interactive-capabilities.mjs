function toPosix(value) {
  return value.split(path.sep).join('/');
}

function walkFiles(root, predicate) {
  const results = [];
  if (!existsSync(root)) return results;
  for (const name of readdirSync(root)) {
    const absolute = path.join(root, name);
    const stat = statSync(absolute);
    if (stat.isDirectory()) results.push(...walkFiles(absolute, predicate));
    else if (predicate(absolute)) results.push(absolute);
  }
  return results;
}

function stripRustComments(source) {
  return source.replace(/\/\*[\s\S]*?\*\//gu, '').replace(/\/\/.*$/gmu, '');
}

export function parseRegisteredCommands(source) {
  const match = source.match(/\.invoke_handler\(tauri::generate_handler!\[([\s\S]*?)\]\)/u);
  if (!match) throw new Error('Desktop invoke_handler registration block was not found');
  const entries = stripRustComments(match[1])
    .split(',')
    .map((entry) => entry.trim())
    .filter(Boolean);
  const invalid = entries.filter((entry) => !/^[A-Za-z0-9_:]+$/u.test(entry));
  if (invalid.length) throw new Error(`Unsupported invoke_handler entries: ${invalid.join(', ')}`);
  return entries.map((rustPath) => ({ id: rustPath.split('::').at(-1), rustPath }));
}

function findBalancedFunctionEnd(source, start) {
  let parenDepth = 0;
  let angleDepth = 0;
  let bracketDepth = 0;
  let inString = false;
  let escaped = false;
  for (let index = start; index < source.length; index += 1) {
    const char = source[index];
    if (inString) {
      if (escaped) escaped = false;
      else if (char === '\\') escaped = true;
      else if (char === '"') inString = false;
      continue;
    }
    if (char === '"') inString = true;
    else if (char === '(') parenDepth += 1;
    else if (char === ')') parenDepth -= 1;
    else if (char === '<') angleDepth += 1;
    else if (char === '>') angleDepth = Math.max(0, angleDepth - 1);
    else if (char === '[') bracketDepth += 1;
    else if (char === ']') bracketDepth -= 1;
    else if (char === '{' && parenDepth === 0 && angleDepth === 0 && bracketDepth === 0) return index;
  }
  return -1;
}

function collectTauriFunctions() {
  const byName = new Map();
  const rustFiles = walkFiles(DESKTOP_ROOT, (file) => file.endsWith('.rs'));
  const marker = /#\[tauri::command(?:\([^\]]*\))?\]/gu;
  for (const file of rustFiles) {
    const source = readFileSync(file, 'utf8');
    for (const attribute of source.matchAll(marker)) {
      const tailStart = attribute.index + attribute[0].length;
      const tail = source.slice(tailStart);
      const fnMatch = tail.match(/^(?:\s*#\[[^\]]+\])*\s*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+([A-Za-z0-9_]+)\s*\(/u);
      if (!fnMatch) continue;
      const functionStart = tailStart + fnMatch.index + fnMatch[0].indexOf('fn ');
      const functionEnd = findBalancedFunctionEnd(source, functionStart);
      if (functionEnd < 0) throw new Error(`Could not parse command signature in ${file}`);
      const value = {
        name: fnMatch[1],
        sourceFile: toPosix(path.relative(REPO_ROOT, file)),
        signature: source.slice(functionStart, functionEnd).replace(/\s+/gu, ' ').trim(),
      };
      const existing = byName.get(value.name) ?? [];
      existing.push(value);
      byName.set(value.name, existing);
    }
  }
  return byName;
}

export function parseRemotePolicies(source) {
  const policies = new Map();
  const entry = /\(\s*"([^"]+)"\s*,\s*RemoteWorkspacePolicy::([A-Za-z]+)\s*,?\s*\)/gu;
  for (const match of source.matchAll(entry)) {
    if (policies.has(match[1])) throw new Error(`Duplicate remote workspace policy: ${match[1]}`);
    policies.set(match[1], match[2]);
  }
  return policies;
}

function normalizeConditionalSignature(signature) {
  return signature.replace(/\b_([a-z][a-z0-9_]*)\s*:/gu, '$1:');
}

function resolveRegisteredFunction(id, rustPath, allCandidates) {
  const moduleHint = rustPath.split('::').at(-2);
  const moduleCandidates = moduleHint
    ? allCandidates.filter(({ sourceFile }) => {
      const withoutExtension = sourceFile.replace(/\.rs$/u, '');
      return withoutExtension.endsWith(`/${moduleHint}`) || withoutExtension.includes(`/${moduleHint}/`);
    })
    : [];
  const candidates = moduleCandidates.length ? moduleCandidates : allCandidates;
  if (!candidates.length) throw new Error(`Registered command ${id} has no matching #[tauri::command] function`);
  const shapes = new Set(candidates.map(({ signature }) => normalizeConditionalSignature(signature)));
  if (shapes.size !== 1) throw new Error(`Registered command ${id} has incompatible conditional implementations`);
  return candidates.find(({ signature }) => !/\b_[a-z][a-z0-9_]*\s*:/u.test(signature)) ?? candidates[0];
}

function commandModule(sourceFile) {
  const basename = path.basename(sourceFile, '.rs');
  if (basename === 'commands' || basename === 'lib') return basename;
  return basename.replace(/_api$/u, '');
}

function extractSingleQuotedIds(source) {
  return new Set([...source.matchAll(/(?:id|actionId|sceneId):\s*'([^']+)'/gu)].map((match) => match[1]));
}

function extractTypeUnionIds(source, typeName) {
  const match = source.match(new RegExp(`export type ${typeName}\\s*=([\\s\\S]*?);`, 'u'));
  if (!match) throw new Error(`${typeName} union was not found`);
  return new Set([...match[1].matchAll(/'([^']+)'/gu)].map((value) => value[1]));
}

function assertBilingual(capability, field) {
  const zh = capability[`${field}Zh`];
  const en = capability[`${field}En`];
  if (typeof zh !== 'string' || !/[\u3400-\u9fff]/u.test(zh)) {
    throw new Error(`${capability.id}.${field}Zh must contain Chinese text`);
  }
  if (typeof en !== 'string' || !/[A-Za-z]/u.test(en)) {
    throw new Error(`${capability.id}.${field}En must contain English text`);
  }
}

function buildInteractionInventory(roots) {
  const signature = [];
  const files = [];
  const interactionLine = /(?:<(?:button|input|select|textarea)\b|\b(?:type|role)=["'](?:button|checkbox|radio|search|menuitem|option|switch|tab)["']|\bon(?:Click|Change|Submit|Select|Press|DoubleClick|ContextMenu|KeyDown|Drop|DragEnd|Blur)=|<(?:Button|IconButton|Checkbox|Switch|Toggle|Select|MenuItem|DropdownMenuItem|Tabs?|Slider|Input|Textarea)\b|\b(?:definePage|registerProductAction)\s*\(|\b(?:actionId|sceneId|eventName)\s*:|startElementSelection|insert-context-tag)/u;
  for (const relativeRoot of roots) {
    const absoluteRoot = path.join(REPO_ROOT, ...relativeRoot.split('/'));
    if (!existsSync(absoluteRoot) || !statSync(absoluteRoot).isDirectory()) {
      throw new Error(`Reviewed interaction root does not exist: ${relativeRoot}`);
    }
    const sourceFiles = walkFiles(absoluteRoot, (file) => {
      const normalized = toPosix(file);
      return /\.(?:ts|tsx)$/u.test(file)
        && !/\.(?:test|spec|stories|example)\.(?:ts|tsx)$/u.test(file)
        && !normalized.includes('/__tests__/');
    }).sort();
    for (const file of sourceFiles) {
      const relativeFile = toPosix(path.relative(REPO_ROOT, file));
      const matchedLines = readFileSync(file, 'utf8')
        .split(/\r?\n/u)
        .map((line) => line.trim().replace(/\s+/gu, ' '))
        .filter((line) => interactionLine.test(line));
      if (!matchedLines.length) continue;
      signature.push(relativeFile, ...matchedLines);
      files.push({
        sourceFile: relativeFile,
        interactionCount: matchedLines.length,
        digest: createHash('sha256').update(matchedLines.join('\n')).digest('hex'),
      });
    }
  }
  return {
    roots,
    digest: createHash('sha256').update(signature.join('\n')).digest('hex'),
    fileCount: files.length,
    interactionCount: files.reduce((total, file) => total + file.interactionCount, 0),
    files,
  };
}

function validateInteractionContract(source) {
  const contract = source.reviewedInteractionContract;
  if (!contract || !Array.isArray(contract.roots) || typeof contract.digest !== 'string') {
    throw new Error('reviewedInteractionContract must declare roots and a reviewed digest');
  }
  if (JSON.stringify(contract.roots) !== JSON.stringify(REQUIRED_INTERACTION_ROOTS)) {
    throw new Error(`reviewedInteractionContract.roots must be ${JSON.stringify(REQUIRED_INTERACTION_ROOTS)}`);
  }
  const inventory = buildInteractionInventory(contract.roots);
  if (contract.digest !== inventory.digest) {
    throw new Error(
      'User-visible UI interactions changed. Audit the feature/setting inventories and their evidence, '
      + `then set reviewedInteractionContract.digest to ${inventory.digest}`,
    );
  }
  return inventory;
}

function validateValueSchema(schema, owner) {
  if (!schema || !['boolean', 'string', 'integer', 'number', 'object', 'array'].includes(schema.type)) {
    throw new Error(`${owner} needs a supported value schema`);
  }
  if (schema.enum && (!Array.isArray(schema.enum) || schema.enum.length === 0)) {
    throw new Error(`${owner}.valueSchema.enum must be a non-empty array`);
  }
}

function validateSource(source) {
  if (source.schemaVersion !== 3) throw new Error('Interactive capability source must use schemaVersion 3');
  const capabilityIds = new Set();
  const settingsSource = readFileSync(SETTINGS_REGISTRY, 'utf8');
  const settingsIds = new Set(
    [...settingsSource.matchAll(/definePage\(\{\s*id:\s*'([^']+)'/gu)].map((match) => match[1]),
  );
  const settingsViewIds = extractTypeUnionIds(readFileSync(SETTINGS_TYPES, 'utf8'), 'SettingsViewId');
  const actionIds = extractSingleQuotedIds(readFileSync(PRODUCT_ACTION_CATALOG, 'utf8'));
  const sceneIds = new Set([
    ...readFileSync(SCENE_TYPES, 'utf8').matchAll(/^\s*\|\s*'([^']+)'/gmu),
  ].map((match) => match[1]));

  const validateDestination = (destination, owner) => {
    if (destination.kind === 'settings') {
      if (!settingsIds.has(destination.pageId)) {
        throw new Error(`${owner} targets unknown settings page ${destination.pageId}`);
      }
      if (destination.viewId && !settingsViewIds.has(destination.viewId)) {
        throw new Error(`${owner} targets unknown settings view ${destination.viewId}`);
      }
      return;
    }
    if (destination.kind === 'action' && !actionIds.has(destination.actionId)) {
      throw new Error(`${owner} targets unknown product action ${destination.actionId}`);
    }
    if (destination.kind === 'scene' && !sceneIds.has(destination.sceneId)) {
      throw new Error(`${owner} targets unknown scene ${destination.sceneId}`);
    }
    if (destination.kind === 'event' && !/^bitfun:[a-z0-9-]+$/u.test(destination.eventName)) {
      throw new Error(`${owner} has an invalid UI event destination`);
    }
    if (!['settings', 'action', 'scene', 'event'].includes(destination.kind)) {
      throw new Error(`${owner} has an unsupported destination`);
    }
  };

  for (const capability of source.capabilities) {
    if (!/^(feature|setting)\.[a-z0-9.-]+$/u.test(capability.id)) {
      throw new Error(`Invalid user-facing capability ID: ${capability.id}`);
    }
    if (capabilityIds.has(capability.id)) throw new Error(`Duplicate capability ID: ${capability.id}`);
    capabilityIds.add(capability.id);
    if (!['feature', 'setting'].includes(capability.kind)) throw new Error(`${capability.id} needs kind feature or setting`);
    if (!source.categories[capability.categoryId]) throw new Error(`${capability.id} has an unknown category`);
    for (const field of ['title', 'summary']) assertBilingual(capability, field);
    for (const field of ['keywordsZh', 'keywordsEn', 'highlightsZh', 'highlightsEn', 'stepsZh', 'stepsEn', 'agentExamplesZh', 'agentExamplesEn']) {
      if (!Array.isArray(capability[field]) || capability[field].length === 0) {
        throw new Error(`${capability.id}.${field} must be a non-empty array`);
      }
    }
    for (const field of ['highlights', 'steps', 'agentExamples']) {
      if (capability[`${field}Zh`].length !== capability[`${field}En`].length) {
        throw new Error(`${capability.id}.${field} must have matching Chinese and English entries`);
      }
    }
    const minimumItems = capability.kind === 'feature' ? 6 : 4;
    if (!Array.isArray(capability.items) || capability.items.length < minimumItems) {
      throw new Error(`${capability.id}.items must document at least ${minimumItems} user-visible sub-capabilities`);
    }
    const itemIds = new Set();
    for (const item of capability.items) {
      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/u.test(item.id ?? '')) {
        throw new Error(`${capability.id} has an invalid documented item ID: ${item.id ?? '<missing>'}`);
      }
      if (itemIds.has(item.id)) throw new Error(`${capability.id} has duplicate documented item ${item.id}`);
      itemIds.add(item.id);
      assertBilingual({ ...item, id: `${capability.id}.${item.id}` }, 'title');
      if (item.destination) {
        validateDestination(item.destination, `${capability.id}.${item.id}`);
        if (
          item.destination.kind === 'settings'
          && capability.destination.kind === 'settings'
          && item.destination.pageId !== capability.destination.pageId
        ) {
          throw new Error(`${capability.id}.${item.id} must stay inside its owning settings page`);
        }
      }
      if (!Array.isArray(item.evidence) || item.evidence.length === 0) {
        throw new Error(`${capability.id}.${item.id}.evidence must not be empty`);
      }
    }

    validateDestination(capability.destination, capability.id);

    const operationIds = new Set();
    for (const operation of capability.operations ?? []) {
      if (operationIds.has(operation.id)) throw new Error(`${capability.id} has duplicate operation ${operation.id}`);
      operationIds.add(operation.id);
      assertBilingual({ ...operation, id: `${capability.id}.${operation.id}` }, 'title');
      assertBilingual({ ...operation, id: `${capability.id}.${operation.id}` }, 'description');
      if (!operation.inputSchema || operation.inputSchema.type !== 'object') {
        throw new Error(`${capability.id}.${operation.id} needs an object input schema`);
      }
      if (
        operation.inputSchema.additionalProperties !== false
        || Object.keys(operation.inputSchema.properties ?? {}).length > 0
      ) {
        throw new Error(
          `${capability.id}.${operation.id} declares operation arguments, but its handler cannot consume them`,
        );
      }
      if (operation.handler.kind !== 'productAction' || !actionIds.has(operation.handler.actionId)) {
        throw new Error(`${capability.id}.${operation.id} has an unsupported operation handler`);
      }
    }

    const optionIds = new Set();
    for (const option of capability.options ?? []) {
      if (capability.kind !== 'setting') throw new Error(`${capability.id} exposes options but is not a setting`);
      if (optionIds.has(option.id)) throw new Error(`${capability.id} has duplicate option ${option.id}`);
      optionIds.add(option.id);
      assertBilingual({ ...option, id: `${capability.id}.${option.id}` }, 'title');
      assertBilingual({ ...option, id: `${capability.id}.${option.id}` }, 'description');
      validateValueSchema(option.valueSchema, `${capability.id}.${option.id}`);
      if (option.handler.kind === 'config' && !option.handler.path) {
        throw new Error(`${capability.id}.${option.id} needs a config path`);
      }
      if (option.handler.kind === 'mergeConfig' && (!option.handler.path || !option.handler.fields?.length)) {
        throw new Error(`${capability.id}.${option.id} needs a merge path and fields`);
      }
      if (!['config', 'mergeConfig', 'appearanceSelection', 'language'].includes(option.handler.kind)) {
        throw new Error(`${capability.id}.${option.id} has an unsupported option handler`);
      }
    }
  }

  const documentedItemCount = source.capabilities.reduce(
    (total, capability) => total + capability.items.length,
    0,
  );
  if (source.reviewedDocumentedItemCount !== documentedItemCount) {
    throw new Error(
      `Documented item count changed from reviewed ${source.reviewedDocumentedItemCount} to ${documentedItemCount}. `
      + 'Complete the source-evidence review, then update reviewedDocumentedItemCount in the same catalog.',
    );
  }

  const semanticSettings = new Set(source.capabilities
    .filter(({ kind }) => kind === 'setting')
    .map(({ destination }) => destination.kind === 'settings' ? destination.pageId : null)
    .filter(Boolean));
  const missingSettings = [...settingsIds].filter((id) => !semanticSettings.has(id));
  const staleSettings = [...semanticSettings].filter((id) => !settingsIds.has(id));
  if (missingSettings.length || staleSettings.length) {
    throw new Error([
      missingSettings.length ? `Settings pages missing from the semantic manual: ${missingSettings.join(', ')}` : '',
      staleSettings.length ? `Semantic settings without a registered page: ${staleSettings.join(', ')}` : '',
    ].filter(Boolean).join('\n'));
  }

  const semanticSettingsViews = new Set(source.capabilities.flatMap((capability) =>
    capability.items
      .map(({ destination }) => destination?.kind === 'settings' ? destination.viewId : null)
      .filter(Boolean)));
  const missingSettingsViews = [...settingsViewIds].filter((id) => !semanticSettingsViews.has(id));
  const staleSettingsViews = [...semanticSettingsViews].filter((id) => !settingsViewIds.has(id));
  if (missingSettingsViews.length || staleSettingsViews.length) {
    throw new Error([
      missingSettingsViews.length
        ? `Settings views missing direct semantic destinations: ${missingSettingsViews.join(', ')}`
        : '',
      staleSettingsViews.length
        ? `Semantic destinations without registered settings views: ${staleSettingsViews.join(', ')}`
        : '',
    ].filter(Boolean).join('\n'));
  }

  for (const [label, owners, actual] of [
    ['product action', source.productActionOwners, actionIds],
    ['scene', source.sceneOwners, sceneIds],
  ]) {
    const ownerIds = new Set(Object.keys(owners ?? {}));
    const missing = [...actual].filter((id) => !ownerIds.has(id));
    const stale = [...ownerIds].filter((id) => !actual.has(id));
    if (missing.length || stale.length) {
      throw new Error([
        missing.length ? `${label}s missing semantic owners: ${missing.join(', ')}` : '',
        stale.length ? `Semantic ${label} owners without registry entries: ${stale.join(', ')}` : '',
      ].filter(Boolean).join('\n'));
    }
    for (const [id, capabilityId] of Object.entries(owners)) {
      if (!capabilityIds.has(capabilityId)) {
        throw new Error(`${label} ${id} targets unknown capability ${capabilityId}`);
      }
    }
  }
  return capabilityIds;
}

function parseSourceEvidence(reference, owner) {
  const separator = reference.indexOf('#');
  if (separator <= 'source:'.length || separator === reference.length - 1) {
    throw new Error(`${owner} has invalid source evidence: ${reference}`);
  }
  const relativePath = reference.slice('source:'.length, separator);
  const marker = reference.slice(separator + 1);
  if (relativePath.includes('..') || !/^(?:src|docs)\//u.test(relativePath)) {
    throw new Error(`${owner} source evidence must stay inside src/ or docs/: ${relativePath}`);
  }
  const absolutePath = path.join(REPO_ROOT, ...relativePath.split('/'));
  if (!existsSync(absolutePath) || !statSync(absolutePath).isFile()) {
    throw new Error(`${owner} source evidence file does not exist: ${relativePath}`);
  }
  const source = readFileSync(absolutePath, 'utf8');
  let markerExists = source.includes(marker);
  if (!markerExists && relativePath.endsWith('.json')) {
    try {
      let value = JSON.parse(source);
      for (const segment of marker.split('.')) {
        if (!value || typeof value !== 'object' || !Object.hasOwn(value, segment)) {
          value = undefined;
          break;
        }
        value = value[segment];
      }
      markerExists = value !== undefined;
    } catch {}
  }
  if (!markerExists) {
    throw new Error(`${owner} source evidence marker is missing from ${relativePath}: ${marker}`);
  }
}

function validateDocumentationEvidence(source, technicalCommands) {
  const commandIds = new Set(technicalCommands.map(({ id }) => id));
  for (const capability of source.capabilities) {
    capability.items.forEach((item) => {
      const owner = `${capability.id}.${item.id}`;
      const references = item.evidence;
      for (const reference of references) {
        if (typeof reference !== 'string') throw new Error(`${owner} references must be strings`);
        if (reference.startsWith('command:')) {
          const commandId = reference.slice('command:'.length);
          if (!commandIds.has(commandId)) throw new Error(`${owner} references unknown command ${commandId}`);
        } else if (reference.startsWith('source:')) {
          parseSourceEvidence(reference, owner);
        } else {
          throw new Error(`${owner} has unsupported evidence: ${reference}`);
        }
      }
    });
  }
}

